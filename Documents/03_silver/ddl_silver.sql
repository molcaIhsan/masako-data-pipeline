  SELECT business_date INTO NEW.business_date FROM silver.shift_instance WHERE shift_instance_id = NEW.shift_instance_id;
  IF NEW.kind = 'reject_override' AND NOT EXISTS (
       SELECT 1 FROM silver.asset_tags t WHERE t.tag_id = NEW.override_tag_id
          AND t.tag_role = 'reject' AND t.uom_id = NEW.entered_uom_id) THEN
    RAISE EXCEPTION 'override_tag_id % must be a reject node whose unit is the entered unit', NEW.override_tag_id;
  END IF;
  RETURN NEW;
END $$;

