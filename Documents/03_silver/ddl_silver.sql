-- EDITING (approved 2026-10-02). Fact rows are never changed; people write APPEND-ONLY edit/entry tables.
--   silver.* = shopfloor: shift open .. 48 h after shift end.   gold.* (ddl_gold.sql) = report: after that.
--   An approved report (gold.report_approval) is frozen: no edits in either domain until it is reopened.
--   The edit row IS the trail (who, when, old -> new, required reason; void instead of delete) and every insert or
--   void also writes one silver.audit_log row (PRD F-14: same transaction, append-only).
--   Views (ddl_views.sql) apply: gold edit > silver edit > machine value; latest non-voided edit per field wins.
-- =====================================================================

-- Clock used by the edit-window rule; tests may pin it with: SET silver.now_override = '2026-09-30 09:00+00';
CREATE FUNCTION silver.fn_now() RETURNS timestamptz LANGUAGE sql STABLE AS $$
  SELECT coalesce(nullif(current_setting('silver.now_override', true), '')::timestamptz, now())
$$;

-- Common trigger: append-only. DELETE refused; UPDATE only to void a live row (voided_at, voided_by, void_reason).
CREATE FUNCTION silver.trg_append_only() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION '%.% is append-only: void the row instead of deleting it', TG_TABLE_SCHEMA, TG_TABLE_NAME;
  END IF;
  IF OLD.voided_at IS NOT NULL THEN
    RAISE EXCEPTION '%.%: row is already voided', TG_TABLE_SCHEMA, TG_TABLE_NAME;
  END IF;
  IF NEW.voided_at IS NULL OR NEW.voided_by IS NULL OR coalesce(btrim(NEW.void_reason), '') = '' THEN
    RAISE EXCEPTION '%.%: an update must void the row (voided_at, voided_by, void_reason)', TG_TABLE_SCHEMA, TG_TABLE_NAME;
  END IF;
  IF (to_jsonb(NEW) - ARRAY['voided_at','voided_by','void_reason'])
     IS DISTINCT FROM (to_jsonb(OLD) - ARRAY['voided_at','voided_by','void_reason']) THEN
    RAISE EXCEPTION '%.%: only voided_at, voided_by and void_reason may change', TG_TABLE_SCHEMA, TG_TABLE_NAME;
  END IF;
  RETURN NEW;
END $$;

-- Common trigger: one silver.audit_log row per insert (create) and per void, in the same transaction.
-- TG_ARGV[0] = module_code, TG_ARGV[1] = id column name.
CREATE FUNCTION silver.trg_edit_audit() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE j jsonb := to_jsonb(NEW);
BEGIN
  INSERT INTO silver.audit_log (occurred_at, domain_code, module_code, action, entity_type, entity_id, entity_code,
                                changes, reason, source, transaction_id, actor_type, actor_subject_id, actor_display_name)
  VALUES (now(), 'PROD', TG_ARGV[0],
          CASE WHEN TG_OP = 'INSERT' THEN 'create' ELSE 'void' END,
          TG_TABLE_SCHEMA || '.' || TG_TABLE_NAME,
          (j ->> TG_ARGV[1])::bigint,
          coalesce(j ->> 'source_event_id', j ->> 'kind'),
          CASE WHEN TG_OP = 'INSERT'
               THEN jsonb_strip_nulls(j - ARRAY['reason','created_by','created_by_name','created_at',
                                                'voided_at','voided_by','void_reason'])
               ELSE jsonb_build_object('voided_at', j -> 'voided_at', 'voided_by', j -> 'voided_by') END,
          CASE WHEN TG_OP = 'INSERT' THEN j ->> 'reason' ELSE j ->> 'void_reason' END,
          'app', txid_current(), 'user',
          CASE WHEN TG_OP = 'INSERT' THEN j ->> 'created_by' ELSE j ->> 'voided_by' END,
          CASE WHEN TG_OP = 'INSERT' THEN j ->> 'created_by_name' ELSE NULL END);
  RETURN NULL;
END $$;

-- Edit window: silver = until 48 h after shift end, gold = after that; approved report = frozen everywhere.
CREATE FUNCTION silver.fn_assert_edit_window(p_domain text, p_shift_instance_id bigint, p_work_unit_id bigint)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE v_end timestamptz; v_status text;
BEGIN
  SELECT end_datetime INTO v_end FROM silver.shift_instance WHERE shift_instance_id = p_shift_instance_id;
  IF v_end IS NULL THEN
    RAISE EXCEPTION 'unknown shift_instance_id %', p_shift_instance_id;
  END IF;
  SELECT status INTO v_status FROM gold.report_approval
   WHERE shift_instance_id = p_shift_instance_id AND work_unit_id = p_work_unit_id;
  IF v_status = 'approved' THEN
    RAISE EXCEPTION 'report (work unit %, shift %) is approved: reopen it before editing', p_work_unit_id, p_shift_instance_id;
  END IF;
  IF p_domain = 'silver' AND silver.fn_now() > v_end + interval '48 hours' THEN
    RAISE EXCEPTION 'shift % ended more than 48 h ago: edit it in gold', p_shift_instance_id;
  END IF;
  IF p_domain = 'gold' AND silver.fn_now() <= v_end + interval '48 hours' THEN
    RAISE EXCEPTION 'shift % is still in the shopfloor window (48 h): edit it in silver', p_shift_instance_id;
  END IF;
END $$;

