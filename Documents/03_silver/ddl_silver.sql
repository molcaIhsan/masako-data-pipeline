-- ---------------------------------------------------------------------
-- FUNCTION: final work unit(s) of each work center on a business date (decided 2026-10-02)
-- equipment_flow is the linked list of machines inside a work center (from_work_unit_id -> to_work_unit_id).
-- A FINAL work unit has no outgoing edge on that date; parallel finals are all returned (summed by the caller).
-- Work-center finished good (good_out) = Σ good of these work units; everything else = Σ of all work units.
-- A work unit with no edge at all counts as final, so a work center without any flow rows = all its work units.
-- ---------------------------------------------------------------------
CREATE FUNCTION silver.fn_work_center_final_work_units(p_business_date date)
RETURNS TABLE (work_center_id bigint, work_unit_id bigint)
LANGUAGE sql STABLE AS $$
  SELECT wu.work_center_id, wu.work_unit_id
  FROM silver.work_unit wu
  WHERE wu.valid_from <= p_business_date
    AND (wu.valid_to IS NULL OR wu.valid_to >= p_business_date)
    AND NOT EXISTS (
      SELECT 1 FROM silver.equipment_flow f
      WHERE f.work_center_id    = wu.work_center_id
        AND f.from_work_unit_id = wu.work_unit_id
        AND f.valid_from <= p_business_date
        AND (f.valid_to IS NULL OR f.valid_to > p_business_date))
$$;
-- ---------------------------------------------------------------------
-- fn_uom_factor: multiply a quantity in p_from by this to get p_to, for one product on one date (PRD PRO-003 / WMS-003).
-- Paths, first that works: same unit · one row forward (×) · one row backward (÷) · two rows via the product's base
-- unit · weight → units via product_detail.standard_weight (PRD KPI-003, shrinkage not applied).
-- NULL = no path ("cannot compute"; never guessed).
-- ---------------------------------------------------------------------
CREATE FUNCTION silver.fn_uom_factor(p_product_id bigint, p_from bigint, p_to bigint, p_date date)
RETURNS numeric LANGUAGE sql STABLE AS $$
  WITH c AS (
    SELECT from_uom_id AS f, to_uom_id AS t, conversion_value AS v
    FROM silver.product_uom_conversion
    WHERE product_id = p_product_id AND valid_from <= p_date AND (valid_to IS NULL OR valid_to > p_date)),
  p AS (SELECT base_uom_id AS b FROM silver.product WHERE product_id = p_product_id),
  w AS (SELECT standard_weight AS sw, weight_uom_id AS wu FROM silver.product_detail
        WHERE product_id = p_product_id AND valid_from <= p_date AND (valid_to IS NULL OR valid_to > p_date)
          AND standard_weight > 0 LIMIT 1),
  to_base AS (   -- factor p_from -> base
    SELECT coalesce(
      CASE WHEN p_from = p.b THEN 1::numeric END,
      (SELECT v FROM c WHERE f = p_from AND t = p.b LIMIT 1),
      (SELECT 1 / v FROM c WHERE f = p.b AND t = p_from LIMIT 1),
      (SELECT 1 / w.sw FROM w WHERE w.wu = p_from)) AS fac
    FROM p),
  from_base AS ( -- factor base -> p_to
    SELECT coalesce(
      CASE WHEN p_to = p.b THEN 1::numeric END,
      (SELECT v FROM c WHERE f = p.b AND t = p_to LIMIT 1),
      (SELECT 1 / v FROM c WHERE f = p_to AND t = p.b LIMIT 1),
      (SELECT w.sw FROM w WHERE w.wu = p_to)) AS fac
    FROM p)
  SELECT CASE
    WHEN p_from IS NULL OR p_to IS NULL OR p_product_id IS NULL THEN NULL
    WHEN p_from = p_to THEN 1::numeric
    ELSE coalesce(
      (SELECT v FROM c WHERE f = p_from AND t = p_to LIMIT 1),
      (SELECT 1 / v FROM c WHERE f = p_to AND t = p_from LIMIT 1),
      (SELECT to_base.fac * from_base.fac FROM to_base, from_base))
  END
$$;

-- ---------------------------------------------------------------------
-- fn_cycle_time: ideal seconds per item of the operation's item unit, for a product on a work unit on a date
-- (PRD WMS-003: station override, else the step; primary released routing of the product at the work unit's
-- work center; a class-based step matches the work unit's class). Discrete/batch only (cycle_time_value).
-- ---------------------------------------------------------------------
CREATE FUNCTION silver.fn_cycle_time(p_work_unit_id bigint, p_product_id bigint, p_date date)
RETURNS TABLE (ct_s numeric, op_uom_id bigint, batch_size integer, operation_id bigint)
LANGUAGE sql STABLE AS $$
  SELECT coalesce(owu.cycle_time_value, o.cycle_time_value) * tc.seconds_per_unit,
         o.uom_id, coalesce(nullif(o.batch_size, 0), 1), o.operation_id
  FROM silver.work_unit wu
  JOIN silver.routing r
    ON r.product_id = p_product_id AND r.work_center_id = wu.work_center_id
   AND r.status = 'released' AND r.is_primary
   AND r.valid_from <= p_date AND (r.valid_to IS NULL OR r.valid_to > p_date)
  JOIN silver.operation o
    ON o.routing_id = r.routing_id
   AND (o.work_unit_id = wu.work_unit_id
        OR (o.work_unit_id IS NULL AND o.required_work_unit_class_id = wu.work_unit_class_id))
   AND o.valid_from <= p_date AND (o.valid_to IS NULL OR o.valid_to > p_date)
  JOIN silver.time_conversions tc ON tc.time_conversions_id = o.time_conversion_id
  LEFT JOIN silver.operation_work_unit owu
    ON owu.operation_id = o.operation_id AND owu.work_unit_id = wu.work_unit_id
   AND owu.valid_from <= p_date AND (owu.valid_to IS NULL OR owu.valid_to > p_date)
  WHERE wu.work_unit_id = p_work_unit_id AND o.cycle_time_value > 0
  ORDER BY o.step_number
  LIMIT 1
$$;

