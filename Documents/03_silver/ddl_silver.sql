CREATE FUNCTION silver.trg_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION '%.% is an immutable trail: no UPDATE or DELETE', TG_TABLE_SCHEMA, TG_TABLE_NAME;
END $$;
